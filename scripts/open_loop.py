"""Open-loop DN responses of the registered real subgraphs to a constant one-eye loom.

Usage: ``FLYCONN_CACHE=... uv run python scripts/open_loop.py``. No physics. Writes
``docs/results/open-loop-looming.md``. This is the probe disclosed in ``docs/metrics.md``.
"""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd
from flyconn.data.store import Store

from flyconn_gym.brain import V2_VARIANTS
from flyconn_gym.coupling import LevelAPolicy
from flyconn_gym.iomap import IOMap
from flyconn_gym.subgraph import load_subgraph

DATASETS = ("malecns@1.0", "banc@888", "flywire@783")
STEPS = 300  # ms
LOOM = 1.0


def main() -> None:
    rows: list[dict[str, object]] = []
    sizes: list[str] = []
    for ref in DATASETS:
        io = IOMap.load(Path("data/iomaps/looming@1") / f"{ref}.json")
        m = load_subgraph(Store.open(ref), io, k=3, min_weight=5)
        sizes.append(f"- {ref}: {m.n} neurons, {m.weights.nnz} edges")
        for variant in V2_VARIANTS[:3]:
            for side, feat in (("left", [LOOM, 0.0]), ("right", [0.0, LOOM])):
                policy = LevelAPolicy.build(m, io, variant, seed=0)
                policy.reset()
                for _ in range(STEPS):
                    policy.act(np.array(feat))
                row: dict[str, object] = {"dataset": ref, "variant": variant.value, "loom": side}
                row.update({k: round(v, 4) for k, v in policy.last_readouts.items()})
                rows.append(row)
    df = pd.DataFrame(rows)
    lines = [
        "# Open-loop DN readouts under a constant one-eye loom",
        "",
        f"Generated by `scripts/open_loop.py` on {datetime.now(UTC):%Y-%m-%d}. Brain only, no "
        f"body: input {LOOM} to one eye's loom set for {STEPS} ms (rate model, seed 0), then the",
        "mean rate of each readout set. Rates are dimensionless (tanh units, max 1). Subgraphs:",
        "k=3, min_weight=5.",
        "",
        *sizes,
        "",
        df.to_markdown(index=False),
        "",
    ]
    out = Path("docs/results/open-loop-looming.md")
    out.write_text("\n".join(lines))
    print(df.to_string())


if __name__ == "__main__":
    main()

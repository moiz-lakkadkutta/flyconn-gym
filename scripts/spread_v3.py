"""Run the pre-registered spread-v3 robustness checks (docs/metrics.md) and summarise them.

Usage (real datasets need FLYCONN_CACHE):
  ``uv run python scripts/spread_v3.py --coverage``          choose matched min_weights
  ``uv run python scripts/spread_v3.py --dataset D --condition A|B|C-v2|C-s``
  ``uv run python scripts/spread_v3.py --summarize``         headline + reading tables
Writes ``runs/spread-v3/...`` and ``docs/results/spread-v3*.md``.
"""

from __future__ import annotations

import argparse
import json
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, cast

import numpy as np
import pandas as pd

from flyconn_gym.brain import V3_VARIANTS
from flyconn_gym.coupling import DNDecoder, LevelAPolicy
from flyconn_gym.datasets import REAL_DATASETS, SUBGRAPH_MIN_WEIGHT, load_looming
from flyconn_gym.env import LoomingWalkEnv
from flyconn_gym.metrics import spread_v2
from flyconn_gym.rollout import replay_drive, run_episode, symmetric

# Registered in docs/metrics.md (spread-v3); do not change.
CONFIRM_SEEDS = range(10, 30)
EXPLORE_SEEDS = range(0, 10)
N_BOOT = 100_000
MW_GRID = (5, 6, 7, 8, 10, 12, 15, 20, 25, 30, 40, 50)
COVERAGE_SETS = ("turn_left", "turn_right", "escape")
CALIBRATION_REFERENCE = 1.0
CALIBRATION_STEPS = 300
DECODER = DNDecoder(tonic=1.0, forward_gain=0.25, turn_gain=0.5, backward_gain=0.5, escape_gain=0.5)
CONDITIONS = {
    # name: (scale mode, coverage-matched subgraph, seeds)
    "A": ("own", False, range(0, 30)),
    "B": ("shared", False, CONFIRM_SEEDS),
    "C-v2": ("own", True, CONFIRM_SEEDS),
    "C-s": ("shared", True, CONFIRM_SEEDS),
}
NULLS = ("rewired", "sign_shuffled", "lat_rewired")
RUNS = Path("runs/spread-v3")
RESULTS = Path("docs/results")
STEPS = 800


def coverage() -> None:
    from flyconn_gym.subgraph import readout_coverage

    grid: dict[str, dict[int, dict[str, float]]] = {}
    for ds in REAL_DATASETS:
        grid[ds] = {}
        for mw in MW_GRID:
            m, io = load_looming(ds, min_weight=mw)
            grid[ds][mw] = {"coverage": readout_coverage(m, io, COVERAGE_SETS), "n": m.n}
            print(ds, mw, grid[ds][mw], flush=True)
    target = min(grid[ds][SUBGRAPH_MIN_WEIGHT]["coverage"] for ds in REAL_DATASETS)
    chosen = {
        ds: min(MW_GRID, key=lambda mw: (abs(grid[ds][mw]["coverage"] - target), mw))
        for ds in REAL_DATASETS
    }
    RUNS.mkdir(parents=True, exist_ok=True)
    (RUNS / "coverage.json").write_text(
        json.dumps({"target": target, "chosen": chosen, "grid": grid}, indent=2)
    )
    rows = [
        {"dataset": ds, "min_weight": mw, "neurons": g["n"], "coverage": round(g["coverage"], 4)}
        for ds, by in grid.items()
        for mw, g in by.items()
    ]
    lines = [
        "# spread-v3 coverage matching (check 4)",
        "",
        f"Generated by `scripts/spread_v3.py --coverage` on {datetime.now(UTC):%Y-%m-%d}, before",
        "any v3 episode. Coverage = mean over turn_left, turn_right and escape readout neurons",
        "of simulated input synapses / whole-dataset input total; k = 3.",
        "",
        f"Target T = {target:.4f} (min over datasets at min_weight 5). Chosen min_weight: "
        + ", ".join(
            f"{ds} {mw} (coverage {grid[ds][mw]['coverage']:.4f}, {grid[ds][mw]['n']} neurons)"
            for ds, mw in chosen.items()
        )
        + ".",
        "",
        pd.DataFrame(rows).to_markdown(index=False),
        "",
    ]
    (RESULTS / "spread-v3-coverage.md").write_text("\n".join(lines))


def _matched_mw(dataset: str) -> int:
    path = RUNS / "coverage.json"
    if not path.exists():
        raise SystemExit("run --coverage first")
    return int(json.loads(path.read_text())["chosen"][dataset])


def run(dataset: str, condition: str) -> None:
    mode, matched, seeds = CONDITIONS[condition]
    mw = _matched_mw(dataset) if matched else SUBGRAPH_MIN_WEIGHT
    if matched and mw == SUBGRAPH_MIN_WEIGHT:
        raise SystemExit(f"{dataset} keeps min_weight 5: its {condition} is the A/B run")
    out = RUNS / condition / dataset
    out.mkdir(parents=True, exist_ok=True)
    m, io = load_looming(dataset, min_weight=mw)
    print(f"{dataset} {condition}: min_weight {mw}, {m.n} neurons", flush=True)

    policies: dict[tuple[str, int], LevelAPolicy] = {}
    own: dict[tuple[str, int], dict[str, float]] = {}
    for seed in seeds:
        for v in V3_VARIANTS:
            p = LevelAPolicy.build(m, io, v, seed=seed)
            p.decoder = DECODER
            own[(v.value, seed)] = p.calibrate(CALIBRATION_REFERENCE, CALIBRATION_STEPS)
            policies[(v.value, seed)] = p
    real_raw_turn = own[("real", seeds[0])].get("turn", 0.0)
    shared: dict[str, float] | None = None
    if mode == "shared":
        groups = {g for s in own.values() for g in s}
        shared = {g: max(s.get(g, 0.0) for s in own.values()) for g in groups}
        for p in policies.values():
            p.use_scale(shared)

    envs = {side: LoomingWalkEnv(max_steps=STEPS, loom_side=side) for side in ("left", "right")}
    rows: list[dict[str, Any]] = []
    t0 = time.perf_counter()
    for seed in seeds:
        for v in V3_VARIANTS:
            policy = policies[(v.value, seed)]
            for side, env in envs.items():
                ep = run_episode(env, policy, seed=seed)
                rep = replay_drive(env, symmetric(ep["drive"]), seed=seed)
                names = ep["dn_names"]
                raw = dict(zip(names, ep["dn_raw"].mean(axis=0), strict=True))
                norm = dict(zip(names, ep["dn"].mean(axis=0), strict=True))
                asym = float(raw.get("turn_left", 0.0) - raw.get("turn_right", 0.0))
                s = ep["summary"]
                rows.append(
                    {
                        "condition": condition,
                        "dataset": dataset,
                        "min_weight": mw,
                        "variant": v.value,
                        "seed": seed,
                        "side": side,
                        "dheading_deg": s["final_heading_deg"],
                        "dheading_replay_deg": rep["final_heading_deg"],
                        "path_length_mm": s["path_length_mm"],
                        "hit": s["hit"],
                        "flipped": s["flipped"],
                        "raw_turn_asym": asym,
                        "raw_turn_asym_ratio": asym / real_raw_turn
                        if real_raw_turn > 0
                        else np.nan,
                        "scale_turn_used": policy.scale_groups.get("turn", 0.0),
                        "scale_turn_own": own[(v.value, seed)].get("turn", 0.0),
                        **{f"dn_{k}": float(x) for k, x in norm.items()},
                    }
                )
        print(f"seed {seed} done ({time.perf_counter() - t0:.0f}s)", flush=True)
    for env in envs.values():
        env.close()
    pd.DataFrame(rows).to_csv(out / "episodes.csv", index=False)
    unshuffled = {
        k: p.brain.matrix.provenance.get("unshuffled_edges")
        for k, p in policies.items()
        if k[0] == "lat_rewired" and p.brain is not None
    }
    meta = {
        "condition": condition,
        "dataset": dataset,
        "min_weight": mw,
        "n_neurons": m.n,
        "n_edges": int(m.weights.nnz),
        "scale_mode": mode,
        "shared_scale": shared,
        "real_raw_turn_scale": real_raw_turn,
        "lat_unshuffled_edges_max": max((u or 0) for u in unshuffled.values()),
        "wall_s": round(time.perf_counter() - t0, 1),
    }
    (out / "meta.json").write_text(json.dumps(meta, indent=2, default=str))
    print(f"wrote {out} in {meta['wall_s']:.0f}s", flush=True)


def _runs() -> list[tuple[str, str, int]]:
    """(condition, dataset, min_weight) of every registered run that should exist."""
    out: list[tuple[str, str, int]] = []
    for cond, (_, matched, _) in CONDITIONS.items():
        for ds in REAL_DATASETS:
            mw = _matched_mw(ds) if matched else SUBGRAPH_MIN_WEIGHT
            if matched and mw == SUBGRAPH_MIN_WEIGHT:
                continue
            out.append((cond, ds, mw))
    return out


def _fmt(r: pd.Series) -> str:
    return f"{r['mean']:+.2f} ({r['bonf_lo']:+.2f} to {r['bonf_hi']:+.2f}) {r['verdict']}"


def summarize() -> None:
    runs = _runs()
    m = 3 * len(runs)
    level = 1 - 0.05 / m
    rows: list[dict[str, Any]] = []
    brain_rows: list[dict[str, Any]] = []
    checks: list[str] = []
    asym: list[pd.DataFrame] = []
    explore: list[dict[str, Any]] = []
    for cond, ds, mw in runs:
        d = RUNS / cond / ds
        ep = pd.read_csv(d / "episodes.csv")
        meta = json.loads((d / "meta.json").read_text())
        conf = cast("pd.DataFrame", ep[ep["seed"].isin(list(CONFIRM_SEEDS))])
        res = spread_v2(conf, n_comparisons=m, n_boot=N_BOOT)
        checks.append(
            f"- {cond} / {ds} (min_weight {mw}, {meta['n_neurons']} neurons): replay check "
            f"{res['replay_check']}; lat_rewired unshuffled edges (max) "
            f"{meta['lat_unshuffled_edges_max']}; turn scale "
            + (
                f"shared {meta['shared_scale'].get('turn', 0):.2e}"
                if meta["shared_scale"]
                else "per brain"
            )
            + f"; real raw S_turn {meta['real_raw_turn_scale']:.2e}."
        )
        for _, w in res["wiring_effect"].iterrows():
            rows.append({"condition": cond, "dataset": ds, **w.to_dict()})
        for _, b in res["brain_effect"].iterrows():
            brain_rows.append({"condition": cond, "dataset": ds, **b.to_dict()})
        wired = cast("pd.DataFrame", ep[ep["variant"] != "no_brain"])
        cols = ["raw_turn_asym", "raw_turn_asym_ratio"]
        a = cast("pd.DataFrame", wired.groupby(["variant", "side"])[cols].mean()).reset_index()
        a.insert(0, "dataset", ds)
        a.insert(0, "condition", cond)
        asym.append(a)
        if cond == "A":
            ex = cast("pd.DataFrame", ep[ep["seed"].isin(list(EXPLORE_SEEDS))])
            r0 = spread_v2(ex, n_comparisons=m, n_boot=N_BOOT)
            for _, w in r0["wiring_effect"].iterrows():
                explore.append({"dataset": ds, **w.to_dict()})
    wiring = pd.DataFrame(rows)
    wiring.to_csv(RUNS / "wiring_effect.csv", index=False)
    brain = pd.DataFrame(brain_rows)

    def verdict(cond: str, ds: str, null: str) -> str:
        keep = (wiring["condition"] == cond) & (wiring["dataset"] == ds) & (wiring["null"] == null)
        found = cast("pd.Series", wiring.loc[keep, "verdict"]).tolist()
        return str(found[0]) if found else "n/a"

    v2_claims = [
        ("malecns@1.0", "rewired", "real > null"),
        ("malecns@1.0", "sign_shuffled", "real > null"),
        ("flywire@783", "rewired", "real > null"),
        ("flywire@783", "sign_shuffled", "real > null"),
        ("banc@888", "rewired", "real < null"),
    ]
    surv = []
    for ds, null, claim in v2_claims:
        va, vb = verdict("A", ds, null), verdict("B", ds, null)
        status = (
            "not run"
            if "n/a" in (va, vb)
            else "survives"
            if va == claim and vb == claim
            else "normalisation-dependent"
            if va == claim
            else "does not replicate"
        )
        surv.append({"v2 claim": f"{ds}: {claim} ({null})", "A": va, "B": vb, "status": status})
    table = wiring.assign(result=wiring.apply(_fmt, axis=1)).pivot_table(
        index=["condition", "dataset"], columns="null", values="result", aggfunc="first"
    )
    lines = [
        "# spread-v3 headline (robustness of spread-v2)",
        "",
        f"Generated by `scripts/spread_v3.py --summarize` on {datetime.now(UTC):%Y-%m-%d}. "
        "**Level A.** Registered in `docs/metrics.md` (spread-v3).",
        f"Confirmatory seeds 10-29 (n = 20). m = {m} comparisons; intervals are Bonferroni at "
        f"{100 * level:.3f} % ({N_BOOT:,} bootstrap resamples, seed 0). Values: paired",
        "E_real - E_null in degrees of turn-away (replay-corrected).",
        "",
        "## Survival of the v2 claims (rule: same verdict in A and in B)",
        "",
        pd.DataFrame(surv).to_markdown(index=False),
        "",
        "## All wiring comparisons",
        "",
        table.to_markdown(),
        "",
        "## Brain effect E_v per condition (degrees; Bonferroni interval)",
        "",
        brain[["condition", "dataset", "variant", "mean", "sd", "bonf_lo", "bonf_hi"]]
        .round(2)
        .to_markdown(index=False),
        "",
        "## Raw turn asymmetry (descriptive, check 2b)",
        "",
        "Mean over episode of raw turn_left - turn_right (rate units), and its ratio to the",
        "real brain's raw S_turn. Positive = more left-DN activity.",
        "",
        pd.concat(asym).round(5).to_markdown(index=False),
        "",
        "## Exploratory: condition A on seeds 0-9 (seen before the v2 registration)",
        "",
        pd.DataFrame(explore)[["dataset", "null", "mean", "ci_lo", "ci_hi", "bonf_lo", "bonf_hi"]]
        .round(2)
        .to_markdown(index=False),
        "",
        "## Run checks",
        "",
        *checks,
        "",
    ]
    (RESULTS / "spread-v3.md").write_text("\n".join(lines))
    print("\n".join(lines[:30]))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--coverage", action="store_true")
    ap.add_argument("--dataset")
    ap.add_argument("--condition", choices=list(CONDITIONS))
    ap.add_argument("--summarize", action="store_true")
    args = ap.parse_args()
    if args.coverage:
        coverage()
    elif args.summarize:
        summarize()
    elif args.dataset and args.condition:
        run(args.dataset, args.condition)
    else:
        ap.error("give --coverage, --summarize, or --dataset with --condition")


if __name__ == "__main__":
    main()

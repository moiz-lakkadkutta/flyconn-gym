"""Run the pre-registered spread-v1 design (docs/metrics.md) on one connectome.

Usage: ``uv run python scripts/spread.py [--dataset toy|malecns@1.0|...] [--seeds 10]``.
Real datasets use the registered k-hop subgraph (needs ``FLYCONN_CACHE``). Writes
``runs/spread-v1/<dataset>/episodes.csv`` + ``summary.json`` and
``docs/results/spread-v1-<dataset>.md``.
"""

from __future__ import annotations

import argparse
import json
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, cast

import pandas as pd
from flyconn.graph import ConnectivityMatrix

from flyconn_gym.brain import BrainVariant
from flyconn_gym.coupling import COUPLING_LEVEL, LevelAPolicy
from flyconn_gym.env import LoomingWalkEnv
from flyconn_gym.iomap import IOMap
from flyconn_gym.metrics import spread_v1
from flyconn_gym.rollout import run_episode
from flyconn_gym.toy import toy_connectome, toy_iomap

# Registered in docs/metrics.md ("spread-v1 on real-connectome subgraphs"); do not change.
SUBGRAPH_K = 3
SUBGRAPH_MIN_WEIGHT = 5


def load(dataset: str) -> tuple[ConnectivityMatrix, IOMap]:
    if dataset == "toy":
        m = toy_connectome()
        return m, toy_iomap(m)
    from flyconn.data.store import Store

    from flyconn_gym.subgraph import load_subgraph

    io = IOMap.load(Path("data/iomaps/looming@1") / f"{dataset}.json")
    m = load_subgraph(Store.open(dataset), io, k=SUBGRAPH_K, min_weight=SUBGRAPH_MIN_WEIGHT)
    return m, io


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", default="toy")
    ap.add_argument("--seeds", type=int, default=10)
    ap.add_argument("--steps", type=int, default=800)
    args = ap.parse_args()
    out = Path("runs/spread-v1") / args.dataset
    report = Path(f"docs/results/spread-v1-{args.dataset}.md")
    out.mkdir(parents=True, exist_ok=True)

    m, io = load(args.dataset)
    print(f"{args.dataset}: {m.n} neurons, {m.weights.nnz} edges", flush=True)
    rows: list[dict[str, Any]] = []
    prov: dict[str, Any] = {}
    t0 = time.perf_counter()
    for side in ("left", "right"):
        env = LoomingWalkEnv(max_steps=args.steps, loom_side=side)
        for seed in range(args.seeds):
            for variant in BrainVariant:
                policy = LevelAPolicy.build(m, io, variant, seed=seed)
                ep = run_episode(env, policy, seed=seed)
                s = ep["summary"]
                dn_mean = dict(zip(ep["dn_names"], ep["dn"].mean(axis=0), strict=True))
                rows.append(
                    {
                        "variant": variant.value,
                        "seed": seed,
                        "side": side,
                        "dheading_deg": s["final_heading_deg"],
                        "min_loom_distance_mm": s["min_loom_distance_mm"],
                        "path_length_mm": s["path_length_mm"],
                        "hit": s["hit"],
                        "flipped": s["flipped"],
                        "steps": s["steps"],
                        **{f"dn_{k}": float(v) for k, v in dn_mean.items()},
                    }
                )
                prov.setdefault(variant.value, ep["provenance"])
            print(f"{side} seed {seed} done ({time.perf_counter() - t0:.0f}s)", flush=True)
        env.close()
    wall = time.perf_counter() - t0

    episodes = pd.DataFrame(rows)
    episodes.to_csv(out / "episodes.csv", index=False)
    res = spread_v1(episodes)
    cols = ["min_loom_distance_mm", "path_length_mm", "hit", "flipped"]
    cols += sorted(c for c in episodes.columns if c.startswith("dn_"))
    secondary = cast("pd.DataFrame", episodes.groupby("variant")[cols].mean())
    summary = {
        "metric": "spread-v1",
        "coupling_level": COUPLING_LEVEL,
        "dataset": io.dataset,
        "iomap": io.label(),
        "n_neurons": m.n,
        "n_edges": int(m.weights.nnz),
        "matrix_provenance": m.provenance,
        "seeds": args.seeds,
        "steps": args.steps,
        "wall_s": round(wall, 1),
        "brain_effect": res["brain_effect"].to_dict("records"),
        "wiring_effect": res["wiring_effect"].to_dict("records"),
        "secondary": secondary.reset_index().to_dict("records"),
        "provenance_by_variant": prov,
    }
    (out / "summary.json").write_text(json.dumps(summary, indent=2, default=str))

    raw_drift = episodes[episodes["variant"] == "no_brain"].groupby("side")["dheading_deg"]
    report.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        f"# spread-v1 on {args.dataset}",
        "",
        f"Generated by `scripts/spread.py` on {datetime.now(UTC):%Y-%m-%d}; metric defined in",
        "`docs/metrics.md` (pre-registered). **Level A.** "
        + (
            "Synthetic toy connectome: not biology."
            if args.dataset == "toy"
            else f"k-hop subgraph (k={SUBGRAPH_K}, min_weight={SUBGRAPH_MIN_WEIGHT}): "
            f"{m.n} neurons, {m.weights.nnz} edges; the rest of the brain is silent."
        ),
        f"{args.seeds} seeds x 2 sides x 4 variants, {args.steps} ms each; wall {wall:.0f} s.",
        "",
        "## Controller drift (no_brain, raw Δheading in degrees)",
        "",
        raw_drift.agg(["mean", "std", "min", "max"]).round(2).to_markdown(),
        "",
        "## Brain effect E_v (drift-corrected turn-away, degrees)",
        "",
        res["brain_effect"].round(2).to_markdown(index=False),
        "",
        "## Wiring effect (paired E_real - E_null, degrees)",
        "",
        res["wiring_effect"].round(2).to_markdown(index=False),
        "",
        "## Secondary (descriptive, per-variant means)",
        "",
        secondary.round(3).to_markdown(),
        "",
    ]
    report.write_text("\n".join(lines))
    print(f"wrote {out}/ and {report} in {wall:.0f}s")


if __name__ == "__main__":
    main()

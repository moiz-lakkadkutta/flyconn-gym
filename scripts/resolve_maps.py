"""Resolve I/O map specs against cached flyconn stores; write id lists and a report.

Usage: ``FLYCONN_CACHE=/path/to/cache uv run python scripts/resolve_maps.py``. Reads only the
neuron tables (no edges). Writes ``data/iomaps/<spec>/<dataset>.json`` and
``docs/iomaps.md``. Every number in that report comes from this script.
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pandas as pd
from flyconn.data.store import Store

from flyconn_gym.maps import SPECS, aliases_from_column, resolve

DATASETS = ("malecns@1.0", "banc@888", "flywire@783")
# FlyWire names are carried over from MaleCNS's own cross-reference column.
ALIAS_SOURCE = {"flywire@783": ("malecns@1.0", "fafb_783_cell_type")}
NOT_APPLICABLE = {"manc@1.2.1": "nerve cord only: no optic-lobe looming inputs"}


def _store_prov(store: Store) -> dict[str, Any]:
    p = store.provenance
    keep = ("registry_ref", "converter", "converter_version", "created_utc", "level", "license")
    return {
        **{k: p.get(k) for k in keep},
        "inputs": [{"name": i["name"], "sha256": i["sha256"]} for i in p.get("inputs", [])],
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path("data/iomaps"))
    ap.add_argument("--report", type=Path, default=Path("docs/iomaps.md"))
    args = ap.parse_args()

    neurons = {ref: Store.open(ref).neurons() for ref in DATASETS}
    lines = [
        "# Resolved I/O maps",
        "",
        f"Generated by `scripts/resolve_maps.py` on {datetime.now(UTC):%Y-%m-%d}. "
        "Do not edit by hand. Citations in the specs are UNVERIFIED until checked.",
        "`side` is each dataset's own side column; neurons without a side are left out of",
        "sided sets.",
        "",
    ]
    for key, spec in SPECS.items():
        lines += [f"## {key}", "", spec.notes, ""]
        table: dict[str, pd.Series] = {}
        for ref in DATASETS:
            aliases: dict[str, str] = {}
            if ref in ALIAS_SOURCE:
                src, col = ALIAS_SOURCE[ref]
                types = {t for s in spec.sets.values() for t in s.cell_types}
                aliases = aliases_from_column(neurons[src], col, sorted(types))
            io, report = resolve(spec, neurons[ref], ref, aliases=aliases)
            store = Store.open(ref)
            io.save(
                args.out / key / f"{ref}.json",
                extra={"store": _store_prov(store), "aliases": aliases},
            )
            cells: dict[str, str] = {}
            for name, r in report.to_dict("index").items():
                miss = f"; missing {r['missing_types']}" if r["missing_types"] else ""
                cells[str(name)] = f"{r['n']} ({r['by_type']}){miss}"
            table[ref] = pd.Series(cells)
            print(ref, report["n"].to_dict())
        df = pd.DataFrame(table)
        df.index.name = "set"
        lines += [df.to_markdown(), ""]
        lines += ["| set | citation |", "|---|---|"]
        lines += [f"| {k} | {s.citation} |" for k, s in spec.sets.items()]
        lines += [""]
        for ref, why in NOT_APPLICABLE.items():
            lines.append(f"- {ref}: not applicable ({why}).")
        lines.append("")
    args.report.write_text("\n".join(lines))
    print(f"wrote {args.report} and {args.out}/")


if __name__ == "__main__":
    main()

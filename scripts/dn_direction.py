"""DN-direction check: clamp DN readouts, drive the body through the decoder, measure turning.

Usage: ``uv run python scripts/dn_direction.py [--seeds 10] [--steps 300]``.
Writes ``docs/results/dn-direction.md``. Positive = turn to the fly's left, relative to
the tonic-only run on the same seed.
"""

from __future__ import annotations

import argparse
import time
from datetime import UTC, datetime
from pathlib import Path

from flyconn_gym.checks import dn_direction

LEVELS = (0.001, 0.01, 0.1, 0.25, 0.5)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=10)
    ap.add_argument("--steps", type=int, default=300)
    ap.add_argument("--report", type=Path, default=Path("docs/results/dn-direction.md"))
    args = ap.parse_args()

    conditions = {f"{side}={a}": {side: a} for side in ("turn_left", "turn_right") for a in LEVELS}
    t0 = time.perf_counter()
    df = dn_direction(conditions, range(args.seeds), steps=args.steps)
    wall = time.perf_counter() - t0
    table = (
        df.groupby("condition", sort=False)["vs_quiet_deg"]
        .agg(["mean", "std", "min", "max"])
        .round(2)
    )
    lines = [
        "# DN-direction check (Level A, no brain)",
        "",
        f"Generated by `scripts/dn_direction.py` on {datetime.now(UTC):%Y-%m-%d}; "
        f"{args.seeds} seeds, {args.steps} ms per run, wall {wall:.0f} s.",
        "DN readouts are clamped and passed through the default `DNDecoder`. The value is the",
        "heading change minus the tonic-only run on the same seed, in degrees; positive is a",
        "turn to the fly's left. Papers: unilateral DNa02 turns the fly toward the active side",
        "(Yang et al. 2024 Cell; Rayshubskiy et al. 2025 eLife).",
        "",
        table.to_markdown(),
        "",
    ]
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(lines))
    print(table.to_string())
    print(f"wrote {args.report} in {wall:.0f}s")


if __name__ == "__main__":
    main()
